#!/usr/bin/env node
// Aggregates judge scores (docs/ui-climb/scores/<round>/<judge>.json, schema in
// docs/ui-climb/judge-schema.json) into docs/ui-climb/scoreboard.md.
//
//   node scripts/ui-scoreboard.mjs [--scores docs/ui-climb/scores] [--out docs/ui-climb/scoreboard.md]
//
// Rules from docs/ui-climb/plan.md: a page is judged by Sol + Opus until their mean reaches 8.5
// (the gate); from then on all four judges score it, and the climb is done when every page's
// four-judge mean is ≥ 9.0 (the target). A page's score is the mean of its non-null dimensions.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = parseArgs(process.argv.slice(2));
const scoresDir = path.resolve(root, args.scores ?? 'docs/ui-climb/scores');
const outFile = path.resolve(root, args.out ?? 'docs/ui-climb/scoreboard.md');

const GATE = 8.5;
const TARGET = 9.0;
const GATE_JUDGES = ['sol', 'opus'];
const ALL_JUDGES = ['opus', 'sol', 'fable', 'astra'];
const PAGES = ['home', 'search', 'course', 'schools', 'school', 'department', 'instructor', 'forum', 'thread', 'auth', 'settings', 'profile', 'landscape', 'legal'];
const DIMENSIONS = ['task', 'hierarchy', 'density', 'viz', 'family', 'type', 'mobile', 'theme', 'a11y', 'states', 'copy', 'feel'];

const rounds = await loadRounds(scoresDir);
const markdown = render(rounds);
await writeFile(outFile, markdown);
console.log(`Wrote ${path.relative(root, outFile)} (${rounds.length} round${rounds.length === 1 ? '' : 's'})`);

/** @returns {Promise<Array<{round: number, judges: Record<string, Record<string, {mean: number, scores: object, top_issues: string[], keep: string[]}>>}>>} */
async function loadRounds(dir) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  const rounds = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const number = Number(entry.name.replace(/^r/, ''));
    if (!Number.isFinite(number)) continue;
    const judges = {};
    for (const file of await readdir(path.join(dir, entry.name))) {
      if (!file.endsWith('.json')) continue;
      const data = JSON.parse(await readFile(path.join(dir, entry.name, file), 'utf8'));
      const judge = String(data.judge ?? file.replace(/\.json$/, '')).toLowerCase();
      judges[judge] = {};
      for (const page of data.pages ?? []) {
        const scores = page.scores ?? {};
        const values = DIMENSIONS.map((d) => scores[d]).filter((v) => typeof v === 'number');
        judges[judge][page.id] = {
          scores,
          // Recompute the mean from the dimensions so a judge's arithmetic cannot skew the board.
          mean: values.length ? values.reduce((a, b) => a + b, 0) / values.length : NaN,
          top_issues: page.top_issues ?? [],
          keep: page.keep ?? []
        };
      }
    }
    rounds.push({ round: number, judges });
  }
  return rounds.sort((a, b) => a.round - b.round);
}

function render(rounds) {
  const lines = ['# UI climb scoreboard', '', `Generated by \`scripts/ui-scoreboard.mjs\` on ${new Date().toISOString().slice(0, 10)}. Gate ${GATE} (Sol + Opus mean, unlocks all four judges) · target ${TARGET} (four-judge mean, every page).`, ''];
  if (!rounds.length) {
    lines.push('_No scores yet. Put judge JSON files in `docs/ui-climb/scores/<round>/<judge>.json`._', '');
    return lines.join('\n');
  }

  const latest = rounds.at(-1);
  lines.push(`## Latest round: r${latest.round}`, '');
  lines.push(`| page | ${ALL_JUDGES.join(' | ')} | gate mean | all-4 mean | status |`);
  lines.push(`| --- | ${ALL_JUDGES.map(() => '---:').join(' | ')} | ---: | ---: | --- |`);
  let done = 0;
  for (const page of PAGES) {
    const cells = ALL_JUDGES.map((judge) => fmt(latest.judges[judge]?.[page]?.mean));
    const gate = meanOf(GATE_JUDGES.map((judge) => latest.judges[judge]?.[page]?.mean));
    const all = meanOf(ALL_JUDGES.map((judge) => latest.judges[judge]?.[page]?.mean));
    const allScored = ALL_JUDGES.every((judge) => Number.isFinite(latest.judges[judge]?.[page]?.mean));
    const status = statusOf(gate, all, allScored);
    if (status === 'done') done++;
    lines.push(`| ${page} | ${cells.join(' | ')} | ${fmt(gate)} | ${fmt(all)} | ${status} |`);
  }
  lines.push('', `**${done} / ${PAGES.length} pages at target.**`, '');

  lines.push('### Per-dimension means (latest round, all judges that scored the page)', '');
  lines.push(`| page | ${DIMENSIONS.join(' | ')} |`);
  lines.push(`| --- | ${DIMENSIONS.map(() => '---:').join(' | ')} |`);
  for (const page of PAGES) {
    const cells = DIMENSIONS.map((d) => fmt(meanOf(ALL_JUDGES.map((judge) => latest.judges[judge]?.[page]?.scores?.[d]))));
    lines.push(`| ${page} | ${cells.join(' | ')} |`);
  }
  lines.push('');

  lines.push('### Top issues (latest round)', '');
  for (const page of PAGES) {
    const issues = ALL_JUDGES.flatMap((judge) => (latest.judges[judge]?.[page]?.top_issues ?? []).map((issue) => `- **${judge}**: ${issue}`));
    const keep = ALL_JUDGES.flatMap((judge) => (latest.judges[judge]?.[page]?.keep ?? []).map((item) => `- _${judge} keep_: ${item}`));
    if (!issues.length && !keep.length) continue;
    lines.push(`#### ${page}`, '', ...issues, ...keep, '');
  }

  if (rounds.length > 1) {
    lines.push('## History (page mean across all judges that scored it)', '');
    lines.push(`| page | ${rounds.map((r) => `r${r.round}`).join(' | ')} |`);
    lines.push(`| --- | ${rounds.map(() => '---:').join(' | ')} |`);
    for (const page of PAGES) {
      const cells = rounds.map((r) => fmt(meanOf(ALL_JUDGES.map((judge) => r.judges[judge]?.[page]?.mean))));
      lines.push(`| ${page} | ${cells.join(' | ')} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

function statusOf(gate, all, allScored) {
  if (!Number.isFinite(gate)) return 'unscored';
  if (gate < GATE) return `below gate (${GATE})`;
  if (!allScored) return 'gate passed · awaiting 4 judges';
  return all >= TARGET ? 'done' : `below target (${TARGET})`;
}

function meanOf(values) {
  const numbers = values.filter((v) => typeof v === 'number' && Number.isFinite(v));
  return numbers.length ? numbers.reduce((a, b) => a + b, 0) / numbers.length : NaN;
}

function fmt(value) {
  return Number.isFinite(value) ? value.toFixed(2) : '—';
}

function parseArgs(argv) {
  const parsed = {};
  for (let i = 0; i < argv.length; i++) {
    if (!argv[i].startsWith('--')) continue;
    const key = argv[i].slice(2);
    const next = argv[i + 1];
    if (next && !next.startsWith('--')) {
      parsed[key] = next;
      i++;
    } else parsed[key] = true;
  }
  return parsed;
}
